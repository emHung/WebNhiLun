-- VolunteerHub initial schema. Apply only to a new/empty Supabase project.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id text unique,
  name text not null,
  email text not null unique,
  phone text,
  dob date,
  city text,
  role text not null default 'volunteer' check (role in ('volunteer','organizer','admin')),
  role_title text not null default 'Tình nguyện viên',
  avatar_url text,
  bio text,
  skills text[] not null default '{}',
  verified_hours integer not null default 0 check (verified_hours >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organizations (
  id text primary key,
  owner_id uuid references public.profiles(id) on delete set null,
  name text not null,
  representative text not null,
  category text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  verified boolean not null default false,
  doc_url text,
  doc_name text,
  registered_at date not null default current_date,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  color_hex text not null default '#10B981'
);

create unique index if not exists organizations_owner_id_unique
  on public.organizations(owner_id) where owner_id is not null;

create table if not exists public.activities (
  id text primary key,
  slug text not null unique,
  title text not null,
  category text not null,
  organization_id text references public.organizations(id) on delete restrict,
  organizer_name text not null,
  organizer_verified boolean not null default false,
  event_date date not null,
  event_time text not null,
  deadline_date date,
  city text not null,
  location text not null,
  capacity integer not null check (capacity > 0),
  applied integer not null default 0 check (applied >= 0 and applied <= capacity),
  verified_hours integer not null default 0 check (verified_hours >= 0),
  status text not null default 'draft',
  featured boolean not null default false,
  banner_url text,
  description text not null default '',
  requirements text,
  items_to_bring text,
  contact text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists activities_slug_idx on public.activities(slug);
create index if not exists activities_status_idx on public.activities(status);
create index if not exists activities_city_category_idx on public.activities(city, category);

create table if not exists public.activity_schedules (
  id bigint generated by default as identity primary key,
  activity_id text not null references public.activities(id) on delete cascade,
  step_order integer not null default 1,
  time_frame text not null,
  content text not null,
  unique(activity_id, step_order)
);

create table if not exists public.applications (
  id text primary key,
  activity_id text not null references public.activities(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  legacy_user_id text,
  user_name text not null,
  user_email text not null,
  user_phone text not null default '',
  event_date text,
  shift text not null default 'Toàn thời gian',
  experience text,
  skills text,
  status text not null default 'pending' check (status in ('pending','approved','rejected','cancelled')),
  status_text text,
  reject_reason text,
  checkin_status text not null default 'not_yet' check (checkin_status in ('not_yet','checked_in')),
  verified_hours integer not null default 0 check (verified_hours >= 0),
  has_certificate boolean not null default false,
  applied_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null
);
create sequence if not exists public.application_id_seq;
create sequence if not exists public.certificate_code_seq;
create index if not exists applications_activity_status_idx on public.applications(activity_id, status);
create index if not exists applications_user_idx on public.applications(user_id, applied_at desc);
create unique index if not exists applications_one_active_per_user_activity
  on public.applications(activity_id, user_id)
  where user_id is not null and status not in ('cancelled','rejected');

create table if not exists public.certificates (
  id text primary key,
  certificate_code text not null unique,
  application_id text not null unique references public.applications(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete cascade,
  recipient_name text not null,
  activity_id text references public.activities(id) on delete cascade,
  title text not null,
  issuer text not null,
  hours integer not null check (hours >= 0),
  issue_date date not null default current_date,
  badge_type text not null default 'Chứng nhận hoàn thành',
  qr_verified boolean not null default true,
  pdf_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id text primary key,
  user_id uuid references public.profiles(id) on delete set null,
  icon text,
  type text not null default 'info' check (type in ('success','warning','info','danger')),
  title text not null,
  description text,
  unread boolean not null default true,
  link text,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user_created_idx on public.notifications(user_id, created_at desc);

create table if not exists public.audit_logs (
  id text primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  actor text not null,
  action text not null,
  target text not null,
  details text,
  ip inet,
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  activity_id text not null references public.activities(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, activity_id)
);

create table if not exists public.system_themes (
  id bigint generated by default as identity primary key,
  legacy_id text unique,
  name text not null,
  primary_color text not null,
  cta_color text not null,
  cta_hover_color text,
  surface_color text not null,
  mode text not null default 'light' check (mode in ('light','dark')),
  meaning text,
  is_active boolean not null default false,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists one_active_system_theme on public.system_themes(is_active) where is_active;

-- Supabase grants broad schema defaults in some projects; explicitly deny direct
-- access to private records. FastAPI performs authorization through the API.
revoke all on public.profiles, public.organizations, public.categories, public.activities,
  public.activity_schedules, public.applications, public.certificates, public.notifications,
  public.audit_logs, public.favorites, public.system_themes from anon, authenticated;
grant select on public.categories, public.activities, public.activity_schedules to anon, authenticated;
grant select on public.organizations, public.system_themes to anon, authenticated;
grant select (certificate_code, title, issuer, hours, issue_date, qr_verified) on public.certificates to anon, authenticated;
grant select (id, name, avatar_url, role, verified_hours) on public.profiles to authenticated;
grant update (name, phone, dob, city, avatar_url, bio, skills) on public.profiles to authenticated;

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, name, email, role, role_title)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', split_part(new.email,'@',1)), new.email,
          'volunteer', 'Tình nguyện viên')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at before update on public.profiles for each row execute procedure public.touch_updated_at();
drop trigger if exists organizations_touch_updated_at on public.organizations;
create trigger organizations_touch_updated_at before update on public.organizations for each row execute procedure public.touch_updated_at();
drop trigger if exists activities_touch_updated_at on public.activities;
create trigger activities_touch_updated_at before update on public.activities for each row execute procedure public.touch_updated_at();

