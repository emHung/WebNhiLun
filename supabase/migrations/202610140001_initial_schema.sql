-- FastAPI uses a privileged server-side DB connection and enforces application RBAC.
-- These policies protect browser-facing Supabase access; no anonymous writes are allowed.
drop policy if exists profiles_read_self on public.profiles;
create policy profiles_read_self on public.profiles for select to authenticated using (id = (select auth.uid()));

drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

drop policy if exists organizations_public_approved on public.organizations;
create policy organizations_public_approved on public.organizations for select to anon, authenticated using (status = 'approved');

drop policy if exists organizations_owner_read on public.organizations;
create policy organizations_owner_read on public.organizations for select to authenticated using (owner_id = (select auth.uid()));

drop policy if exists activities_public_visible on public.activities;
create policy activities_public_visible on public.activities for select to anon, authenticated using (status not in ('draft','pending','rejected','Chờ Admin duyệt','Bản nháp'));

drop policy if exists schedules_public_visible on public.activity_schedules;
create policy schedules_public_visible on public.activity_schedules for select to anon, authenticated using (
  exists(select 1 from public.activities a where a.id = activity_id and a.status not in ('draft','pending','rejected','Chờ Admin duyệt','Bản nháp'))
);

drop policy if exists categories_read_all on public.categories;
create policy categories_read_all on public.categories for select to anon, authenticated using (true);

drop policy if exists applications_read_own on public.applications;
create policy applications_read_own on public.applications for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists certificates_read_own on public.certificates;
create policy certificates_read_own on public.certificates for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists notifications_read_own on public.notifications;
create policy notifications_read_own on public.notifications for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists notifications_update_own on public.notifications;
create policy notifications_update_own on public.notifications for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists audit_admin_read on public.audit_logs;
create policy audit_admin_read on public.audit_logs for select to authenticated using (
  exists(select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin')
);

drop policy if exists favorites_manage_own on public.favorites;
create policy favorites_manage_own on public.favorites for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists themes_read_active on public.system_themes;
create policy themes_read_active on public.system_themes for select to anon, authenticated using (is_active);

create or replace function public.verify_certificate(p_code text)
returns table(certificate_code text, recipient_name text, activity_title text, issuer text, hours integer, issue_date date, valid boolean)
language sql stable security definer set search_path = '' as $$
  select c.certificate_code, c.recipient_name, c.title, c.issuer, c.hours, c.issue_date, c.qr_verified
  from public.certificates c
  where c.certificate_code = p_code;
$$;
revoke all on function public.verify_certificate(text) from public;
grant execute on function public.verify_certificate(text) to anon, authenticated;

